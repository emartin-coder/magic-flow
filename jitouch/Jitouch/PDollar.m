// Each built-in is loaded at three widths: $P keeps a drawing's proportions, so a narrow handwritten E drifted
// to I and a narrow K to L against one fixed-width template (alphabet test, 2026-11-24). ponytail: knob.
static const float widthVariants[] = {0.45f, 0.7f, 1.0f, 1.4f};
#define N_BUILTIN (N_SOURCES * (int)(sizeof(widthVariants) / sizeof(widthVariants[0])))
#define MAX_TEMPLATES 512
static PDTemplate templates[MAX_TEMPLATES];
static int nTemplates;

static float dist(PDPoint a, PDPoint b) { return hypotf(a.x - b.x, a.y - b.y); }

static int strokeCount(const PDPoint *p, int n) {
    int count = n > 0;
    for (int i = 1; i < n; i++)
        if (p[i].stroke != p[i - 1].stroke) count++;
    return count;
}
// $P ignores stroke count, but it still tells letters apart: a 3-stroke F shouldn't lose to a 2-stroke P. A template
// written with a different number of strokes scores this much worse (alphabet test, 2026-11-24). ponytail: knob.
static const float strokeCountPenalty = 1.15f;
// Closure: distance from a stroke's start to its end, relative to its size. An O ends where it began; a U, C or V
// doesn't, and $P can't tell. Your trained O measured 0.03-0.16 and your U 0.61-0.85 (2026-11-24), so a one-stroke
// drawing more open than openDrawing never matches a template that closes (below closedShape). ponytail: knobs.
static const float openDrawing = 0.45f, closedShape = 0.2f;
static float closureGap(const PDPoint *p, int n) {
    float minX = FLT_MAX, minY = FLT_MAX, maxX = -FLT_MAX, maxY = -FLT_MAX;
    for (int i = 0; i < n; i++) {
        minX = fminf(minX, p[i].x); maxX = fmaxf(maxX, p[i].x);
        minY = fminf(minY, p[i].y); maxY = fmaxf(maxY, p[i].y);
    }
    return hypotf(p[n - 1].x - p[0].x, p[n - 1].y - p[0].y) / fmaxf(fmaxf(maxX - minX, maxY - minY), 1e-6f);
}
static int isMultiStroke(const PDPoint *p, int n) {
    for (int i = 1; i < n; i++)
        if (p[i].stroke != p[0].stroke) return 1;
    return 0;
}

// Resample to exactly PD_N points spaced evenly along the drawn path (never across a pen lift).
static void resample(const PDPoint *in, int n, PDPoint *out) {
    float len = 0;
    for (int i = 1; i < n; i++)
        if (in[i].stroke == in[i - 1].stroke) len += dist(in[i - 1], in[i]);
    float interval = len / (PD_N - 1), D = 0;
    int k = 0;
    out[k++] = in[0];
    PDPoint prev = in[0];
    for (int i = 1; i < n && k < PD_N; i++) {
        if (in[i].stroke != in[i - 1].stroke) { prev = in[i]; continue; }
        float d = dist(prev, in[i]);
        while (D + d >= interval && d > 0 && k < PD_N) {
            float t = (interval - D) / d;
            PDPoint q = { prev.x + t * (in[i].x - prev.x), prev.y + t * (in[i].y - prev.y), in[i].stroke };
            out[k++] = q;
            d -= interval - D;
            D = 0;
            prev = q;
        }
        D += d;
        prev = in[i];
    }
    while (k < PD_N) out[k++] = in[n - 1]; // rounding can leave the last slot empty
}

// Uniform scale into the unit box (keeps aspect ratio), then center on the centroid.
static void normalize(PDPoint *p) {
    float minX = FLT_MAX, minY = FLT_MAX, maxX = -FLT_MAX, maxY = -FLT_MAX;
    for (int i = 0; i < PD_N; i++) {
        minX = fminf(minX, p[i].x); maxX = fmaxf(maxX, p[i].x);
        minY = fminf(minY, p[i].y); maxY = fmaxf(maxY, p[i].y);
    }
    float size = fmaxf(fmaxf(maxX - minX, maxY - minY), 1e-6f), cx = 0, cy = 0;
    for (int i = 0; i < PD_N; i++) {
        p[i].x = (p[i].x - minX) / size; p[i].y = (p[i].y - minY) / size;
        cx += p[i].x; cy += p[i].y;
    }
    cx /= PD_N; cy /= PD_N;
    for (int i = 0; i < PD_N; i++) { p[i].x -= cx; p[i].y -= cy; }
}

static float cloudDistance(const PDPoint *a, const PDPoint *b, int start) {
    int matched[PD_N] = {0};
    float sum = 0;
    int i = start;
    do {
        int best = -1;
        float min = FLT_MAX;
        for (int j = 0; j < PD_N; j++) {
            if (matched[j]) continue;
            float d = dist(a[i], b[j]);
            if (d < min) { min = d; best = j; }
        }
        matched[best] = 1;
        float weight = 1 - (float)((i - start + PD_N) % PD_N) / PD_N;
        sum += weight * min;
        i = (i + 1) % PD_N;
    } while (i != start);
    return sum;
}

static float greedyCloudMatch(const PDPoint *pts, const PDPoint *tmpl) {
    int step = (int)floor(pow(PD_N, 0.5)); // epsilon = 0.5, as in the paper
    float min = FLT_MAX;
    for (int i = 0; i < PD_N; i += step)
        min = fminf(min, fminf(cloudDistance(pts, tmpl, i), cloudDistance(tmpl, pts, i)));
    return min;
}

// Your own handwriting, recorded with tools/learn.py: one template per line, "LETTER x,y,stroke x,y,stroke ...".
// $P works best with the writer's own examples; built-ins are only the fallback.
static void loadUserTemplates(void) {
    const char *env = getenv("JITOUCH_LETTERS"); // tests point this at a scratch file
    NSString *path = env ? [NSString stringWithUTF8String:env]
                         : [@"~/Library/Application Support/Jitouch/letters.txt" stringByExpandingTildeInPath];
    NSString *text = [NSString stringWithContentsOfFile:path encoding:NSUTF8StringEncoding error:NULL];
    for (NSString *line in [text componentsSeparatedByString:@"\n"]) {
        NSArray *parts = [[line stringByTrimmingCharactersInSet:[NSCharacterSet whitespaceCharacterSet]] componentsSeparatedByString:@" "];
        if ([parts count] < 3 || nTemplates >= MAX_TEMPLATES) continue;
        PDPoint raw[1024];
        int n = 0;
        for (NSUInteger i = 1; i < [parts count] && n < 1024; i++) {
            NSArray *xys = [[parts objectAtIndex:i] componentsSeparatedByString:@","];
            if ([xys count] != 3) continue;
            raw[n++] = (PDPoint){[[xys objectAtIndex:0] floatValue], [[xys objectAtIndex:1] floatValue], [[xys objectAtIndex:2] intValue]};
        }
        if (n < 2) continue;
        templates[nTemplates].name = strdup([[parts objectAtIndex:0] UTF8String]);
        templates[nTemplates].multi = isMultiStroke(raw, n);
        templates[nTemplates].strokes = strokeCount(raw, n);
        templates[nTemplates].gap = closureGap(raw, n);
        resample(raw, n, templates[nTemplates].pts);
        normalize(templates[nTemplates].pts);
        nTemplates++;
    }
}

float pdollarRunnerUp = FLT_MAX;
int pdollarBestIsUser;
const char *pdollarBestUser;
float pdollarBestUserScore = FLT_MAX;
static dispatch_once_t loadOnce;
static void loadTemplates(void);
static const char *pdollarMatch(const PDPoint *pts, int n, float maxScore, float *score, int userOnly);

int pdollarUserTemplateCount(void) {
    loadTemplates();
    return nTemplates - N_BUILTIN;
}

const char *pdollarRecognize(const PDPoint *pts, int n, float maxScore, float *score, int userOnly) {
    loadTemplates();
    *score = FLT_MAX;
    if (n < 2) return NULL;
    return pdollarMatch(pts, n, maxScore, score, userOnly);
}

static void loadTemplates(void) {
    dispatch_once(&loadOnce, ^{
        int t = 0;
        for (int v = 0; v < (int)(sizeof(widthVariants) / sizeof(widthVariants[0])); v++)
            for (int k = 0; k < N_SOURCES; k++, t++) {
                PDPoint scaled[64];
                for (int i = 0; i < sources[k].n; i++)
                    scaled[i] = (PDPoint){sources[k].pts[i].x * widthVariants[v], sources[k].pts[i].y, sources[k].pts[i].stroke};
                templates[t].name = sources[k].name;
                templates[t].multi = isMultiStroke(scaled, sources[k].n);
                templates[t].strokes = strokeCount(scaled, sources[k].n);
                templates[t].gap = closureGap(scaled, sources[k].n);
                resample(scaled, sources[k].n, templates[t].pts);
                normalize(templates[t].pts);
            }
        nTemplates = N_BUILTIN;
        loadUserTemplates();
    });
}

static const char *pdollarMatch(const PDPoint *pts, int n, float maxScore, float *score, int userOnly) {
    // Like with like: you write Y in two strokes, so a single stroke (a scroll, a piece of an F) is never a Y.
    int multi = isMultiStroke(pts, n), strokes = strokeCount(pts, n);
    int open = !multi && closureGap(pts, n) > openDrawing;
    PDPoint cand[PD_N];
    resample(pts, n, cand);
    normalize(cand);
    const char *best = NULL, *second = NULL;
    float secondScore = FLT_MAX, d[MAX_TEMPLATES];
    pdollarBestIsUser = 0;
    pdollarBestUser = NULL;
    pdollarBestUserScore = FLT_MAX;
    int first = userOnly == 1 ? N_BUILTIN : 0, last = userOnly == 2 ? N_BUILTIN : nTemplates; // 1: yours only, 2: built-ins only
    for (int t = first; t < last; t++) {
        d[t] = FLT_MAX;
        if (templates[t].multi != multi) continue;
        if (open && templates[t].gap < closedShape) continue; // an open stroke is never an O
        d[t] = greedyCloudMatch(cand, templates[t].pts) * (templates[t].strokes == strokes ? 1 : strokeCountPenalty);
        if (d[t] < *score) { *score = d[t]; best = templates[t].name; pdollarBestIsUser = t >= N_BUILTIN; }
        if (t >= N_BUILTIN && d[t] < pdollarBestUserScore) { pdollarBestUserScore = d[t]; pdollarBestUser = templates[t].name; }
    }
    for (int t = first; t < last; t++) // runner-up: the best of any other letter
        if (best && d[t] < secondScore && strcmp(templates[t].name, best) != 0) { secondScore = d[t]; second = templates[t].name; }
    pdollarRunnerUp = secondScore;
#ifdef JITOUCH_TRACE
    printf("   $P best %s %.2f, runner-up %s %.2f\n", best, *score, second, secondScore);
#endif
    return *score <= maxScore ? best : NULL;
}
