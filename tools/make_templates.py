arrays, entries = [], []
for key, strokes in letters.items():
    pts = ",".join(f"{{{x:.3f},{y:.3f},{s}}}" for s, st in enumerate(strokes) for x, y in st)
    arrays.append(f"static const PDPoint t{key}[] = {{{pts}}};")
    entries.append(f'T("{key[0]}", t{key})')
print("\n".join(arrays))
print("// ENTRIES: " + ", ".join(entries))
